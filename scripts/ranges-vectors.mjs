// Writes test/ranges-vectors.json from public/ranges.js. route.bible vendors ranges.js and runs
// these same vectors, so both read and write highlights the same way. Run: node scripts/ranges-vectors.mjs
import { writeFileSync } from "node:fs";
import { expandRange, highlightRecord, listRanges, newestFirst, rangeWrites, stamp, tombstone } from "../public/ranges.js";

const h = (ref, color, created, extra = {}) => ({ kind: "highlight", ref, highlights: [{ color, created }], updated: created, ...extra });
const cases = {
  merge: [h("JHN.3.16", "yellow", 100), h("JHN.3.17", "yellow", 110), h("JHN.3.18", "yellow", 105)],
  gap: [h("JHN.3.16", "yellow", 100), h("JHN.3.18", "yellow", 100)],
  chapterBoundary: [h("JHN.3.36", "yellow", 100), h("JHN.4.1", "yellow", 100)],
  bookBoundary: [h("MRK.16.20", "yellow", 100), h("LUK.1.1", "yellow", 100)],
  mixedColors: [h("ROM.5.3", "yellow", 100), h("ROM.5.4", "green", 200), h("ROM.5.5", "green", 150)],
  splitAfterDelete: [h("PSA.23.1", "blue", 100), { kind: "highlight", ref: "PSA.23.2", deleted: true, updated: 300 }, h("PSA.23.3", "blue", 120), h("PSA.23.4", "blue", 90)],
  shrinkAfterDelete: [h("PHP.4.6", "yellow", 100), h("PHP.4.7", "yellow", 100), { kind: "highlight", ref: "PHP.4.8", deleted: true, updated: 300 }],
  recolorNewestPart: [{ kind: "highlight", ref: "JHN.1.1", highlights: [{ color: "yellow", created: 100 }, { color: "pink", created: 100, edited: 200 }], updated: 200 }, h("JHN.1.2", "pink", 150)],
  unknownColorIsYellow: [h("GEN.1.1", "teal", 100), h("GEN.1.2", "yellow", 100)],
  otherKindsIgnored: [h("JHN.3.16", "yellow", 100), { kind: "note", ref: "JHN.3.17", body: "x", updated: 1 }, { kind: "color", ref: "yellow", name: "Y", updated: 1 }],
  outOfOrderInput: [h("JHN.3.18", "yellow", 100), h("JHN.3.16", "yellow", 100), h("JHN.3.17", "yellow", 100)],
};
const view = (runs) => runs.map(({ ref, verses, color, time }) => ({ ref, verses, color, time }));
const ranges = Object.fromEntries(Object.entries(cases).map(([name, records]) => {
  const runs = listRanges(records);
  return [name, { records, canonical: view(runs), newestFirst: view(newestFirst(runs)) }];
}));
const writes = [
  { name: "save new verse", prev: null, ref: "JHN.3.16", color: "yellow", t: 1000 },
  { name: "save over a tombstone in the same second", prev: { kind: "highlight", ref: "JHN.3.16", deleted: true, updated: 1000 }, ref: "JHN.3.16", color: "yellow", t: 1000 },
  { name: "delete", prev: h("JHN.3.16", "yellow", 900), ref: "JHN.3.16", t: 1000, delete: true },
  { name: "delete with clock behind", prev: h("JHN.3.16", "yellow", 1500), ref: "JHN.3.16", t: 1000, delete: true },
].map((w) => {
  const live = w.prev && !w.prev.deleted ? w.prev : null;
  const record = w.delete ? tombstone(w.ref) : highlightRecord(live, w.ref, w.color, w.t);
  return { ...w, expect: JSON.stringify(stamp(record, w.prev?.updated, w.t)) };
});
// Range writes (the reverse of grouping): a canonical range → its verses, then the records to save.
const expand = [
  { ref: "ROM.5.3-5" },
  { ref: "JHN.3.16" },
  { ref: "PSA.119.1-100" },
  { ref: "PSA.119.1-101" },
  { ref: "PSA.119.1-176", max: 176 },
  { ref: "ROM.5" },
  { ref: "ROM.5.5-3" },
  { ref: "ROM.5.3-3" },
  { ref: "ROM.5.3-ROM.6.2" },
  { ref: "XYZ.1.1" },
  { ref: "ROM.17.1" },
].map((c) => ({ ...c, expect: expandRange(c.ref, c.max ? { max: c.max } : {}) }));
const rangeWriteCases = [
  { name: "new range", existing: [], ref: "ROM.5.3-5", color: "green", t: 1000 },
  { name: "repeat is a no-op", existing: [h("ROM.5.3", "green", 900), h("ROM.5.4", "green", 900), h("ROM.5.5", "green", 900)], ref: "ROM.5.3-5", color: "green", t: 1000 },
  { name: "some verses already that color", existing: [h("ROM.5.4", "green", 900)], ref: "ROM.5.3-5", color: "green", t: 1000 },
  { name: "a verse in another color takes the new one", existing: [h("ROM.5.4", "yellow", 900)], ref: "ROM.5.3-5", color: "green", t: 1000 },
  { name: "a partial highlight in that color becomes the whole verse", existing: [{ kind: "highlight", ref: "ROM.5.3", highlights: [{ color: "green", start: 4, end: 9, quote: "glory", created: 900 }], updated: 900 }], ref: "ROM.5.3-4", color: "green", t: 1000 },
  { name: "over a tombstone", existing: [{ kind: "highlight", ref: "ROM.5.3", deleted: true, updated: 900 }], ref: "ROM.5.3", color: "blue", t: 1000 },
  { name: "bad range writes nothing", existing: [], ref: "ROM.5.5-3", color: "green", t: 1000 },
].map((c) => {
  const live = new Map(c.existing.filter((r) => !r.deleted).map((r) => [r.ref, r]));
  const w = rangeWrites(c.ref, c.color, c.t, (v) => live.get(v) ?? null);
  return { ...c, expect: w.error ? { error: w.error } : { ref: w.ref, verses: w.verses, records: w.records.map((r) => JSON.stringify(r)) } };
});
writeFileSync(new URL("../test/ranges-vectors.json", import.meta.url), JSON.stringify({ _note: "Generated by scripts/ranges-vectors.mjs from public/ranges.js. route.bible runs these too.", ranges, writes, expand, rangeWrites: rangeWriteCases }, null, 1) + "\n");
console.log(Object.keys(ranges).length, "range cases,", writes.length, "write cases,", expand.length, "expand cases,", rangeWriteCases.length, "range write cases");
