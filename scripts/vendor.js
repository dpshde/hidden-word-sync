// Copies third-party browser code into public/vendor (the web app has no build step) and keeps the
// CSP in public/_headers in step with it. Run with `bun run vendor` after bumping either package.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const path = (p) => new URL(p, root).pathname;

// grab-bcv: only the parse and books sub-paths; the package root also bundles ~280 KB of paragraph data.
const built = await Bun.build({ entrypoints: [path("scripts/grab-bcv.js")], format: "esm", minify: true });
if (!built.success) throw new AggregateError(built.logs, "grab-bcv bundle failed");
const grab = JSON.parse(readFileSync(path("node_modules/grab-bcv/package.json"), "utf8"));
writeFileSync(
  path("public/vendor/grab-bcv.js"),
  `// grab-bcv ${grab.version} (MIT) https://github.com/dpshde/grab-bcv - generated by \`bun run vendor\`, do not edit\n` +
    (await built.outputs[0].text()),
);

// 1Password's "Save in 1Password" button, as published. It has no imports.
const op = JSON.parse(readFileSync(path("node_modules/@1password/save-button/package.json"), "utf8"));
const button = readFileSync(path("node_modules/@1password/save-button/built/index.js"), "utf8");
writeFileSync(
  path("public/vendor/onepassword-save-button.js"),
  `// @1password/save-button ${op.version} (MIT) https://www.npmjs.com/package/@1password/save-button - copied by \`bun run vendor\`, do not edit\n` +
    button,
);

// The button styles its shadow DOM with one fixed <style> block. Allow exactly that block by hash,
// rather than allowing inline styles in general.
const styles = [...button.matchAll(/<style>([\s\S]*?)<\/style>/g)].map((m) => m[1]);
if (styles.length !== 1 || styles[0].includes("${")) throw new Error("the save button's styles changed shape; update the CSP by hand");
const hash = `'sha256-${createHash("sha256").update(styles[0]).digest("base64")}'`;
const headers = readFileSync(path("public/_headers"), "utf8");
const next = headers.replace(/style-src [^;]*;/, `style-src 'self' ${hash};`);
if (next === headers && !headers.includes(hash)) throw new Error("no style-src in public/_headers");
writeFileSync(path("public/_headers"), next);
console.log(`vendored grab-bcv ${grab.version} and @1password/save-button ${op.version}; style hash ${hash}`);
