// Copies third-party browser code into public/vendor (the web app has no build step) and keeps the
// CSP in public/_headers in step with it. Run with `bun run vendor` after bumping either package.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const path = (p) => new URL(p, root).pathname;
const version = (name) => JSON.parse(readFileSync(path(`node_modules/${name}/package.json`), "utf8")).version;

async function bundle(entry) {
  const built = await Bun.build({ entrypoints: [path(entry)], format: "esm", minify: true, target: "browser" });
  if (!built.success) throw new AggregateError(built.logs, `${entry} bundle failed`);
  return built.outputs[0].text();
}

// grab-bcv: only the parse and books sub-paths; the package root also bundles ~280 KB of paragraph data.
const grab = version("grab-bcv");
writeFileSync(
  path("public/vendor/grab-bcv.js"),
  `// grab-bcv ${grab} (MIT) https://github.com/dpshde/grab-bcv - generated by \`bun run vendor\`, do not edit\n` +
    (await bundle("scripts/grab-bcv.js")),
);

// scripture-inline: the passage field (<si-passage-input>, no requests) and the passage text (<si-passage>,
// which asks YouVersion for a passage only when the app shows one). Bundling tree-shakes away the
// reference scanner and grab-bcv's paragraph data.
const si = version("@faith-tools/scripture-inline");
// A local fix rides on top of the published package (bun patch, listed in package.json): see patches/.
const siPatch = JSON.parse(readFileSync(path("package.json"), "utf8")).patchedDependencies?.[`@faith-tools/scripture-inline@${si}`];
const field = await bundle("scripts/scripture-inline.js");
writeFileSync(
  path("public/vendor/scripture-inline.js"),
  `// @faith-tools/scripture-inline ${si} (MIT, Cameron Pak / Faith Tools Software Solutions, LLC)\n` +
    `// https://github.com/cameronapak/scripture-inline, license in scripture-inline.LICENSE.md - generated by \`bun run vendor\`, do not edit\n` +
    (siPatch ? `// with ${siPatch} applied\n` : "") +
    field,
);
// MIT asks that the notice travel with the code.
writeFileSync(path("public/vendor/scripture-inline.LICENSE.md"), readFileSync(path("node_modules/@faith-tools/scripture-inline/LICENSE.md"), "utf8"));

// Each component styles its shadow root with one fixed <style> block, built when the module loads.
// Build them here in a stand-in DOM and allow exactly those blocks by hash, rather than inline styles in general.
const styles = await shadowStyles(path("public/vendor/scripture-inline.js"));
if (styles.length !== 2) throw new Error(`expected 2 shadow <style> blocks, found ${styles.length}; update the CSP by hand`);
const hashes = styles.map((css) => `'sha256-${createHash("sha256").update(css).digest("base64")}'`);
const headers = readFileSync(path("public/_headers"), "utf8");
const next = headers.replace(/style-src 'self'( 'sha256-[^']+')*/, `style-src 'self' ${hashes.join(" ")}`);
if (!/style-src 'self'/.test(headers)) throw new Error("no style-src 'self' in public/_headers");
writeFileSync(path("public/_headers"), next);

async function shadowStyles(module) {
  const found = [];
  const node = () => ({ style: {}, dataset: {}, setAttribute() {}, removeAttribute() {}, addEventListener() {}, append() {}, replaceChildren() {} });
  const classes = [];
  Object.assign(globalThis, {
    HTMLElement: class {
      attachShadow() {
        return { append: (...nodes) => nodes.forEach((n) => n.tag === "style" && found.push(n.textContent)) };
      }
      attachInternals() { return {}; }
      addEventListener() {}
      setAttribute() {}
    },
    document: { createElement: (tag) => Object.assign(node(), { tag }) },
    matchMedia: () => ({ matches: false, addEventListener() {}, removeEventListener() {} }),
    customElements: { get: () => undefined, define: (_name, c) => classes.push(c) },
  });
  const { definePassageInput, defineScripturePassage } = await import(module);
  definePassageInput();
  defineScripturePassage();
  for (const C of classes) new C();
  return found;
}

console.log(`vendored grab-bcv ${grab} and @faith-tools/scripture-inline ${si}; style hashes ${hashes.join(" ")}`);
